"""
Synthetic end-to-end demo scenario.
Fictional company: Alamo Defense Solutions (not a real entity)
Scenario: CMMC Level 2 readiness assessment, several gaps identified during a mock internal review.
"""
import sqlite3
import sys
import os

sys.path.insert(0, os.path.dirname(__file__))
from crosswalk import load_controls, find_candidates, ask_llm_for_mapping, save_crosswalk, normalize_pcidss_id
from draft_poam import get_control, draft_poam_entry, save_poam
import json

DB_PATH = "data/grc.db"

SCENARIO_GAPS = [
    {
        "control_id": "AC.L2-3.1.1",
        "gap": "Alamo Defense Solutions (fictional test organization) does not maintain a current list of authorized users with system access; access reviews have not been performed in over a year."
    },
    {
        "control_id": "AU.L2-3.3.1",
        "gap": "Audit logs are generated by systems but are not centrally collected or regularly reviewed. No formal log retention policy has been defined."
    },
    {
        "control_id": "IR.L2-3.6.1",
        "gap": "No formal, documented incident response plan exists. Security incidents are currently handled informally on an ad hoc basis by IT staff."
    },
    {
        "control_id": "IA.L2-3.5.3",
        "gap": "Multifactor authentication is not currently enforced for remote access or privileged accounts; password-only authentication is in use."
    },
]

def log_action(conn, action, source_control_id, details):
    conn.execute(
        "INSERT INTO audit_log (action, source_control_id, details) VALUES (?, ?, ?)",
        (action, source_control_id, json.dumps(details))
    )
    conn.commit()

def run_scenario():
    conn = sqlite3.connect(DB_PATH)
    print("=" * 70)
    print("SYNTHETIC DEMO SCENARIO — Alamo Defense Solutions (fictional)")
    print("CMMC Level 2 readiness review — 4 identified gaps")
    print("=" * 70)

    for item in SCENARIO_GAPS:
        cid = item["control_id"]
        gap = item["gap"]

        print(f"\n{'─' * 70}")
        print(f"CONTROL: {cid}")
        print(f"{'─' * 70}")

        cur = conn.execute(
            "SELECT framework, control_id, title, text FROM controls WHERE control_id = ?",
            (cid,)
        )
        row = cur.fetchone()
        if not row:
            print(f"Control {cid} not found — skipping.")
            continue
        framework, _, title, text = row
        print(f"\n[LOOKUP] {framework} {cid} — {title}")
        print(f"{text[:250]}...")

        existing = conn.execute(
            "SELECT pcidss_control_id, confidence, mapping_rationale FROM crosswalk WHERE cmmc_control_id = ?",
            (cid,)
        ).fetchall()

        if existing:
            print(f"\n[CROSSWALK] (cached results)")
            for pid, conf, rationale in existing:
                print(f"  -> PCI-DSS {pid} ({conf}): {rationale[:100]}")
        else:
            pcidss_controls = load_controls(conn, "PCI-DSS")
            cmmc_control = {"control_id": cid, "title": title, "text": text}
            candidates = find_candidates([cmmc_control], pcidss_controls)
            result = ask_llm_for_mapping(cmmc_control, candidates[cid])
            log_action(conn, "crosswalk_attempt", cid, {
                "candidates_considered": [c["control_id"] for c in candidates[cid]],
                "result": result
            })
            mappings = result.get("mappings", [])
            print(f"\n[CROSSWALK] (new query)")
            if not mappings:
                print("  No PCI-DSS mapping found.")
            for mapping in mappings:
                save_crosswalk(conn, cid, mapping)
                print(f"  -> PCI-DSS {normalize_pcidss_id(mapping['pcidss_id'])} ({mapping['confidence']}): {mapping['rationale'][:100]}")

        control = get_control(conn, cid)
        draft = draft_poam_entry(control, gap)
        log_action(conn, "poam_draft", cid, {"gap_description": gap, "draft": draft})

        print(f"\n[POA&M DRAFT] (gap: {gap[:80]}...)")
        if "error" not in draft:
            save_poam(conn, cid, gap, draft)
            print(f"  Remediation: {draft['remediation_plan'][:200]}...")
            print(f"  Timeline: {draft['suggested_timeline']}")
            print(f"  Risk: {draft['risk_if_unaddressed'][:150]}...")
            print(f"  Status: draft_pending_review")
        else:
            print(f"  Failed: {draft.get('error')}")

    print(f"\n{'=' * 70}")
    print("SCENARIO COMPLETE — all outputs saved to database, flagged for human review")
    print(f"{'=' * 70}")

    conn.close()

if __name__ == "__main__":
    run_scenario()
